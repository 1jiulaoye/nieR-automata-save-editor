LEVEL_SIZE: dict[int, int] = {0: 4, 1: 5, 2: 6, 3: 7, 4: 9, 5: 11, 6: 14, 7: 17, 8: 21}

# =============================================================================
# ChipRegistry：名称 ↔ 二进制 双向互转
# =============================================================================


class ChipRegistry:
    """芯片注册表：管理所有芯片的名称↔二进制互转"""

    def __init__(self) -> None:
        self._name_to_bytes: dict[str, bytes] = {}  # 完整 48 字节
        self._bytes_to_name: dict[bytes, str] = {}  # 前 12 字节 → 芯片名
        self._build()

    def _build(self) -> None:
        """构建双向映射表"""
        # 1. 普通芯片：从基地址生成 +0~+8 的所有变体（20字节头 + 补齐）
        for name, base12 in COMMON_CHIPS.items():
            r = struct.unpack("<3i", base12)
            # Level 0
            data20 = base12 + struct.pack("<2i", 0, 4)
            full48 = _fill_record(data20)
            self._name_to_bytes[name] = full48
            self._bytes_to_name[base12] = name
            # Level 1-8
            for lv in range(1, 9):
                nv = struct.pack("<3i", r[0] + lv, r[1] + lv, r[2])
                data20 = nv + struct.pack("<2i", lv, LEVEL_SIZE[lv])
                full48 = _fill_record(data20)
                self._name_to_bytes[name + f" +{lv}"] = full48
                self._bytes_to_name[nv] = name + f" +{lv}"

        # 2. 系统芯片：直接使用 20 字节数据，补齐到 48 字节
        for name, data20 in UNIQUE_CHIPS.items():
            full48 = _fill_record(data20)
            self._name_to_bytes[name] = full48
            self._bytes_to_name[data20[:12]] = name

    # ------------------------------------------------------------------
    # 公共 API
    # ------------------------------------------------------------------

    def to_bytes(self, name: str) -> bytes:
        """芯片名 → 48 字节，未知名称抛 ValueError"""
        try:
            return self._name_to_bytes[name]
        except KeyError:
            raise ValueError(f"未知芯片名称：{name}") from None

    def to_name(self, data: bytes) -> str:
        """前 12 字节 → 芯片名"""
        return self._bytes_to_name.get(data[:12], "未知芯片")

    @property
    def all_names(self) -> tuple[str, ...]:
        """所有可用芯片名（按字母排序）"""
        return tuple(sorted(self._name_to_bytes.keys()))

    @property
    def common_names(self) -> tuple[str, ...]:
        """普通芯片名（不含 +1~+8 变体）"""
        return tuple(sorted(COMMON_CHIPS.keys()))

    @property
    def unique_names(self) -> tuple[str, ...]:
        """系统芯片名"""
        return tuple(sorted(UNIQUE_CHIPS.keys()))


