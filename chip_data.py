def _fill_record(data20: bytes) -> bytes:
    """将 20 字节芯片头补齐为 48 字节完整记录"""
    assert len(data20) == 20, f"data20 must be 20 bytes, got {len(data20)}"
    return data20 + b'\xff' * 24 + b'\x00' * 4

