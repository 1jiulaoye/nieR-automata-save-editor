# 落在区间外、需要单独归类的
EXTRA_CATEGORY: dict[int, str] = {
    0x00AA: "关键道具",
}

# 武器 ID 区间（武器没有堆叠数量概念）
WEAPON_RANGES: tuple[tuple[int, int], ...] = (
    (0x03EB, 0x0442),
    (0x04B3, 0x04F6),
    (0x0578, 0x05C8),
    (0x0640, 0x0672),
    (0x0753, 0x0755),
)

# UI 下拉框顺序（固定，避免排序抖动）
CATEGORY_ORDER: tuple[str, ...] = tuple(name for name, _, _ in CATEGORY_RANGES)

# 各分类条目数（校验 / 展示用）
ITEM_CATEGORIES: dict[str, int] = {}


def get_item_name(item_id: int) -> str:
    """获取道具名称"""
    return ITEM_NAMES.get(item_id, f"未知 (0x{item_id:04X})")


def get_category(item_id: int) -> str:
    """获取道具所属分类（区间互不重叠，先查特殊表）"""
    if item_id in EXTRA_CATEGORY:
        return EXTRA_CATEGORY[item_id]
    for name, start, end in CATEGORY_RANGES:
        if start <= item_id <= end:
            return name
    return "其他"


def is_weapon(item_id: int) -> bool:
    """是否武器"""
    return any(start <= item_id <= end for start, end in WEAPON_RANGES)


def search_items(query: str) -> list[tuple[int, str]]:
    """搜索道具：模糊匹配名称"""
    q = query.lower()
    return [(i, n) for i, n in sorted(ITEM_NAMES.items()) if q in n.lower()]


for _iid in ITEM_NAMES:
    _cat = get_category(_iid)
    ITEM_CATEGORIES[_cat] = ITEM_CATEGORIES.get(_cat, 0) + 1
