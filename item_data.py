ITEM_CATEGORIES: dict[str, tuple[int, int]] = {
    "恢复": (0x0000, 0x0003),
    "状态治疗": (0x0032, 0x005A),
    "战斗增幅": (0x0064, 0x0096),
    "技能速度": (0x008C, 0x00A2),
    "鱼饵/鱼类": (0x012C, 0x0190),
    "材料": (0x01EF, 0x0286),
    "贵重品": (0x028A, 0x031D),
    "关键道具": (0x0340, 0x03A3),
    "DLC道具": (0x03E8, 0x1F50),
}


def get_item_name(item_id: int) -> str:
    """获取道具名称"""
    return ITEM_NAMES.get(item_id, f"未知 (0x{item_id:04X})")


def get_category(item_id: int) -> str:
    """获取道具所属分类"""
    for cat, (start, end) in ITEM_CATEGORIES.items():
        if start <= item_id <= end:
            return cat
    return "其他"


def search_items(query: str) -> list:
    """搜索道具：模糊匹配名称"""
    q = query.lower()
    return [(i, n) for i, n in sorted(ITEM_NAMES.items()) if q in n.lower()]
